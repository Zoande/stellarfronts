export function isSpeciesArchetypeId(value: unknown): value is SpeciesArchetypeId {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(SPECIES_ARCHETYPE_BY_ID, value);
}

export function isSpeciesTraitId(value: unknown): value is SpeciesTraitId {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(SPECIES_TRAIT_BY_ID, value);
}

export function sanitizeSpeciesName(value: unknown, fallback = "Founders"): string {
  const text = typeof value === "string" ? value.trim() : "";
  if (!text) return fallback;
  return text.slice(0, 48);
}

export function validateSpeciesTraits(traitIds: readonly unknown[]): SpeciesTraitValidation {
  const normalizedTraitIds: SpeciesTraitId[] = [];
  const errors: string[] = [];
  const seen = new Set<SpeciesTraitId>();
  for (const raw of traitIds) {
    if (!isSpeciesTraitId(raw)) {
      errors.push("Unknown species trait.");
      continue;
    }
    if (seen.has(raw)) {
      errors.push("Duplicate species traits are not allowed.");
      continue;
    }
    seen.add(raw);
    normalizedTraitIds.push(raw);
  }
  if (normalizedTraitIds.length > SPECIES_TRAIT_MAX_COUNT) {
    errors.push(`Species can have at most ${SPECIES_TRAIT_MAX_COUNT} traits.`);
  }
  const spent = normalizedTraitIds.reduce((sum, traitId) => sum + SPECIES_TRAIT_BY_ID[traitId].pointCost, 0);
  const remainingPoints = SPECIES_TRAIT_POINT_BUDGET - spent;
  if (remainingPoints < 0) {
    errors.push("Species trait point budget exceeded.");
  }
  return {
    valid: errors.length === 0,
    remainingPoints,
    errors,
    normalizedTraitIds,
  };
}

export function normalizeSpeciesSetup(raw: unknown, fallbackName = "Founders"): SpeciesSetup {
  const record = raw && typeof raw === "object" ? raw as Partial<SpeciesSetup> : {};
  const archetypeId = isSpeciesArchetypeId(record.archetypeId) ? record.archetypeId : "humanoid";
  const validation = validateSpeciesTraits(Array.isArray(record.traitIds) ? record.traitIds : []);
  return {
    speciesName: sanitizeSpeciesName(record.speciesName, fallbackName),
    archetypeId,
    traitIds: validation.valid ? validation.normalizedTraitIds : [],
  };
}

export function createDefaultSpeciesForFaction(factionId: number, factionName: string): SpeciesState {
  const preset = DETERMINISTIC_PRESETS[Math.abs(factionId) % DETERMINISTIC_PRESETS.length];
  const setup = normalizeSpeciesSetup(preset, factionName);
  return {
    id: `species-faction-${factionId}`,
    name: setup.speciesName,
    archetypeId: setup.archetypeId,
    traitIds: setup.traitIds,
    originFactionId: factionId,
  };
}

export function createSpeciesFromSetup(factionId: number, setup: SpeciesSetup): SpeciesState {
  const normalized = normalizeSpeciesSetup(setup, `Species ${factionId + 1}`);
  return {
    id: `species-faction-${factionId}`,
    name: normalized.speciesName,
    archetypeId: normalized.archetypeId,
    traitIds: normalized.traitIds,
    originFactionId: factionId,
  };
}

export function normalizeSpeciesState(raw: Partial<SpeciesState> | undefined, fallback: SpeciesState): SpeciesState {
  const archetypeId = isSpeciesArchetypeId(raw?.archetypeId) ? raw.archetypeId : fallback.archetypeId;
  const validation = validateSpeciesTraits(Array.isArray(raw?.traitIds) ? raw.traitIds : fallback.traitIds);
  return {
    id: typeof raw?.id === "string" && raw.id.trim() ? raw.id.trim() : fallback.id,
    name: sanitizeSpeciesName(raw?.name, fallback.name),
    archetypeId,
    traitIds: validation.valid ? validation.normalizedTraitIds : fallback.traitIds,
    originFactionId: Number.isInteger(raw?.originFactionId) ? Number(raw?.originFactionId) : fallback.originFactionId ?? null,
  };
}

function normalizeRightsOption<T extends string>(value: unknown, options: Array<SpeciesRightsOption<T>>, fallback: T): T {
  return options.some((option) => option.id === value) ? value as T : fallback;
}

export function normalizeSpeciesRights(raw: Partial<SpeciesRights> | undefined): SpeciesRights {
  return {
    livingStandard: normalizeRightsOption(raw?.livingStandard, LIVING_STANDARD_OPTIONS, DEFAULT_SPECIES_RIGHTS.livingStandard),
    citizenship: normalizeRightsOption(raw?.citizenship, CITIZENSHIP_OPTIONS, DEFAULT_SPECIES_RIGHTS.citizenship),
    migration: normalizeRightsOption(raw?.migration, MIGRATION_OPTIONS, DEFAULT_SPECIES_RIGHTS.migration),
    workEligibility: normalizeRightsOption(raw?.workEligibility, WORK_ELIGIBILITY_OPTIONS, DEFAULT_SPECIES_RIGHTS.workEligibility),
  };
}

