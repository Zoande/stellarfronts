export type SpeciesId = string;

export type SpeciesArchetypeId = "humanoid" | "avian" | "reptilian" | "aquatic" | "fungoid";

export type SpeciesTraitId =
  | "adaptive"
  | "intelligent"
  | "rapidBreeders"
  | "industrious"
  | "agrarian"
  | "ingenious"
  | "communal"
  | "charismatic"
  | "conservationist"
  | "resilient"
  | "nonadaptive"
  | "slowBreeders"
  | "wasteful"
  | "unruly"
  | "delicate";

export type LivingStandardId = "luxurious" | "comfortable" | "basic" | "subsistence" | "oppressed";
export type CitizenshipStatusId = "fullCitizenship" | "residence" | "limitedRights" | "nonCitizen";
export type MigrationRightsId = "free" | "controlled" | "prohibited";
export type WorkEligibilityId = "allJobs" | "noAuthority" | "laborOnly";
export type SpeciesRightsCategory = "livingStandard" | "citizenship" | "migration" | "workEligibility";

export interface SpeciesArchetypeDefinition {
  id: SpeciesArchetypeId;
  name: string;
  icon: string;
  summary: string;
}

export interface SpeciesTraitDefinition {
  id: SpeciesTraitId;
  name: string;
  pointCost: number;
  polarity: "positive" | "negative";
  description: string;
}

export interface SpeciesState {
  id: SpeciesId;
  name: string;
  archetypeId: SpeciesArchetypeId;
  traitIds: SpeciesTraitId[];
  originFactionId?: number | null;
}

export interface SpeciesSetup {
  speciesName: string;
  archetypeId: SpeciesArchetypeId;
  traitIds: SpeciesTraitId[];
}

export interface SpeciesTraitValidation {
  valid: boolean;
  remainingPoints: number;
  errors: string[];
  normalizedTraitIds: SpeciesTraitId[];
}

export interface SpeciesRights {
  livingStandard: LivingStandardId;
  citizenship: CitizenshipStatusId;
  migration: MigrationRightsId;
  workEligibility: WorkEligibilityId;
}

export interface FactionSpeciesRightsState {
  factionId: number;
  rightsBySpeciesId: Record<SpeciesId, SpeciesRights>;
}

export interface SpeciesRightsOption<TId extends string = string> {
  id: TId;
  name: string;
  summary: string;
  description: string;
}

export interface SpeciesRightsOptionAvailability<TId extends string = string> extends SpeciesRightsOption<TId> {
  allowed: boolean;
  reason?: string;
}

export interface LegalSpeciesRightsOptions {
  livingStandards: Array<SpeciesRightsOptionAvailability<LivingStandardId>>;
  citizenship: Array<SpeciesRightsOptionAvailability<CitizenshipStatusId>>;
  migration: Array<SpeciesRightsOptionAvailability<MigrationRightsId>>;
  workEligibility: Array<SpeciesRightsOptionAvailability<WorkEligibilityId>>;
}

export interface SpeciesLawSelections {
  civilRights?: string;
  speciesPolicy?: string;
}

