function allowedIdsForSpeciesPolicy(category: SpeciesRightsCategory, optionId: string, speciesPolicy = "managedResidency"): boolean {
  if (speciesPolicy === "pluralistProtections") {
    if (category === "livingStandard") return ["luxurious", "comfortable", "basic"].includes(optionId);
    if (category === "citizenship") return ["fullCitizenship", "residence"].includes(optionId);
    if (category === "migration") return ["free", "controlled"].includes(optionId);
    if (category === "workEligibility") return ["allJobs", "noAuthority"].includes(optionId);
  }
  if (speciesPolicy === "stratifiedSpeciesCodes") return true;
  if (category === "livingStandard") return ["comfortable", "basic", "subsistence"].includes(optionId);
  if (category === "citizenship") return ["fullCitizenship", "residence", "limitedRights"].includes(optionId);
  if (category === "migration") return ["free", "controlled", "prohibited"].includes(optionId);
  if (category === "workEligibility") return ["allJobs", "noAuthority"].includes(optionId);
  return true;
}

function allowedByCivilRights(category: SpeciesRightsCategory, optionId: string, civilRights = "civicRegistry"): boolean {
  if (civilRights === "martialRestrictions") return true;
  if (civilRights === "universalFranchise") {
    if (category === "livingStandard" && optionId === "oppressed") return false;
    if (category === "citizenship" && optionId === "nonCitizen") return false;
    if (category === "workEligibility" && optionId === "laborOnly") return false;
  }
  if (category === "livingStandard" && optionId === "oppressed") return false;
  if (category === "workEligibility" && optionId === "laborOnly") return false;
  return true;
}

function optionReason(category: SpeciesRightsCategory, optionId: string, selections: SpeciesLawSelections): string | undefined {
  if (!allowedIdsForSpeciesPolicy(category, optionId, selections.speciesPolicy)) return "Blocked by Species Policy law.";
  if (!allowedByCivilRights(category, optionId, selections.civilRights)) return "Blocked by Civil Rights law.";
  return undefined;
}

function withAvailability<T extends string>(
  category: SpeciesRightsCategory,
  options: Array<SpeciesRightsOption<T>>,
  selections: SpeciesLawSelections,
): Array<SpeciesRightsOptionAvailability<T>> {
  return options.map((option) => {
    const reason = optionReason(category, option.id, selections);
    return { ...option, allowed: !reason, reason };
  });
}

export function getLegalSpeciesRightsOptions(selections: SpeciesLawSelections = {}): LegalSpeciesRightsOptions {
  return {
    livingStandards: withAvailability("livingStandard", LIVING_STANDARD_OPTIONS, selections),
    citizenship: withAvailability("citizenship", CITIZENSHIP_OPTIONS, selections),
    migration: withAvailability("migration", MIGRATION_OPTIONS, selections),
    workEligibility: withAvailability("workEligibility", WORK_ELIGIBILITY_OPTIONS, selections),
  };
}

function clampOption<T extends string>(
  current: T,
  options: Array<SpeciesRightsOptionAvailability<T>>,
  fallback: T,
): T {
  if (options.some((option) => option.id === current && option.allowed)) return current;
  if (options.some((option) => option.id === fallback && option.allowed)) return fallback;
  return options.find((option) => option.allowed)?.id ?? fallback;
}

export function normalizeSpeciesRightsForLaws(raw: Partial<SpeciesRights> | undefined, selections: SpeciesLawSelections = {}): SpeciesRights {
  const rights = normalizeSpeciesRights(raw);
  const legal = getLegalSpeciesRightsOptions(selections);
  return {
    livingStandard: clampOption(rights.livingStandard, legal.livingStandards, DEFAULT_SPECIES_RIGHTS.livingStandard),
    citizenship: clampOption(rights.citizenship, legal.citizenship, DEFAULT_SPECIES_RIGHTS.citizenship),
    migration: clampOption(rights.migration, legal.migration, DEFAULT_SPECIES_RIGHTS.migration),
    workEligibility: clampOption(rights.workEligibility, legal.workEligibility, DEFAULT_SPECIES_RIGHTS.workEligibility),
  };
}

export function getSpeciesEconomyEffects(species: SpeciesState | undefined, rights: SpeciesRights = DEFAULT_SPECIES_RIGHTS): SpeciesEconomyEffects {
  const effects: SpeciesEconomyEffects = {
    habitabilityAdd: 0,
    growthMultiplier: 1,
    housingUsageMultiplier: 1,
    amenitiesMultiplier: 1,
    goodsUpkeepMultiplier: 1,
    happinessAdd: 0,
    crimeAdd: 0,
    stabilityAdd: 0,
  };
  for (const traitId of species?.traitIds ?? []) {
    if (traitId === "adaptive") effects.habitabilityAdd += 10;
    if (traitId === "nonadaptive") effects.habitabilityAdd -= 10;
    if (traitId === "rapidBreeders") effects.growthMultiplier *= 1.1;
    if (traitId === "slowBreeders") effects.growthMultiplier *= 0.9;
    if (traitId === "communal") effects.housingUsageMultiplier *= 0.9;
    if (traitId === "charismatic") effects.amenitiesMultiplier *= 1.1;
    if (traitId === "conservationist") effects.goodsUpkeepMultiplier *= 0.9;
    if (traitId === "wasteful") effects.goodsUpkeepMultiplier *= 1.15;
    if (traitId === "resilient") {
      effects.crimeAdd -= 5;
      effects.stabilityAdd += 1;
    }
    if (traitId === "unruly") effects.crimeAdd += 5;
  }

  if (rights.livingStandard === "luxurious") {
    effects.goodsUpkeepMultiplier *= 1.85;
    effects.happinessAdd += 12;
    effects.crimeAdd -= 6;
    effects.growthMultiplier *= 1.05;
  } else if (rights.livingStandard === "comfortable") {
    effects.goodsUpkeepMultiplier *= 1.25;
    effects.happinessAdd += 5;
    effects.growthMultiplier *= 1.02;
  } else if (rights.livingStandard === "subsistence") {
    effects.goodsUpkeepMultiplier *= 0.75;
    effects.happinessAdd -= 8;
    effects.crimeAdd += 5;
    effects.growthMultiplier *= 0.95;
  } else if (rights.livingStandard === "oppressed") {
    effects.goodsUpkeepMultiplier *= 0.4;
    effects.happinessAdd -= 20;
    effects.crimeAdd += 14;
    effects.growthMultiplier *= 0.88;
  }

  if (rights.citizenship === "fullCitizenship") effects.happinessAdd += 4;
  if (rights.citizenship === "limitedRights") effects.happinessAdd -= 5;
  if (rights.citizenship === "nonCitizen") {
    effects.happinessAdd -= 12;
    effects.crimeAdd += 5;
  }

  if (rights.migration === "free") {
    effects.happinessAdd += 2;
    effects.growthMultiplier *= 1.03;
  } else if (rights.migration === "prohibited") {
    effects.happinessAdd -= 4;
    effects.growthMultiplier *= 0.96;
  }

  if (rights.workEligibility === "noAuthority") effects.happinessAdd -= 2;
  if (rights.workEligibility === "laborOnly") {
    effects.happinessAdd -= 8;
    effects.crimeAdd += 6;
  }
  return effects;
}

export function getSpeciesJobOutputMultiplier(species: SpeciesState | undefined, job: string, resource: string, jobClass: string): number {
  let multiplier = 1;
  for (const traitId of species?.traitIds ?? []) {
    if (traitId === "intelligent" && job === "researcher" && resource === "research") multiplier *= 1.1;
    if (traitId === "industrious" && job === "miner" && resource === "minerals") multiplier *= 1.1;
    if (traitId === "agrarian" && job === "farmer" && resource === "food") multiplier *= 1.1;
    if (traitId === "ingenious" && job === "technician" && resource === "energy") multiplier *= 1.1;
    if (traitId === "delicate" && jobClass === "lower") multiplier *= 0.95;
  }
  return multiplier;
}

export function canRightsWorkJob(rights: SpeciesRights, jobClass: string): boolean {
  if (rights.workEligibility === "allJobs") return true;
  if (rights.workEligibility === "noAuthority") return jobClass !== "upper";
  return jobClass === "lower";
}
